#!/usr/bin/env node
'use strict';
/* Builds each module's browser bundle from modules/<id>/bundle.json:
     modules/<id>/dist/<id>.js    all listed files in one scope, exposed as window.ToolboxModules.<id>
     modules/<id>/dist/<id>.css   the listed stylesheets, in order
   The existing apps were written as one shared scope (their top-level names reach across files), so the bundle keeps that
   shape. It is plain concatenation: no transpiling, no minifying. dist/ is generated (git-ignored); `npm start` and `npm test`
   run this first.  Usage: node tools/build.js [moduleId ...] */
const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const MODULES = path.join(REPO, 'modules');

function buildModule(id) {
  const dir = path.join(MODULES, id);
  const cfg = JSON.parse(fs.readFileSync(path.join(dir, 'bundle.json'), 'utf8'));
  const read = f => fs.readFileSync(path.resolve(dir, f), 'utf8');
  const parts = [];
  parts.push(`/* GENERATED by tools/build.js from modules/${id}/bundle.json. Do not edit; edit the sources. */`);
  parts.push(`(window.ToolboxModules = window.ToolboxModules || {}).${JSON.stringify(id).slice(1, -1).includes('-') ? '["' + id + '"]' : id} = (function () {`);
  parts.push("'use strict';");
  if (cfg.pages) parts.push(`const PAGES_HTML = ${JSON.stringify(read(cfg.pages))};`);
  for (const f of cfg.files) {
    parts.push(`/* ---- ${f.replace(/^(\.\.\/)+/, '')} ---- */`);
    parts.push(read(f).replace(/^'use strict';\s*$/m, ''));
  }
  parts.push('return API;');
  parts.push('})();');
  const out = path.join(dir, 'dist');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, `${id}.js`), parts.join('\n') + '\n');
  fs.writeFileSync(path.join(out, `${id}.css`), (cfg.css || []).map(f => `/* ---- ${f} ---- */\n${read(f)}`).join('\n'));
  return { id, js: fs.statSync(path.join(out, `${id}.js`)).size };
}

function main() {
  const want = process.argv.slice(2);
  const ids = fs.readdirSync(MODULES).filter(d => fs.existsSync(path.join(MODULES, d, 'bundle.json')) && (!want.length || want.includes(d)));
  for (const id of ids) { const r = buildModule(id); console.log(`built modules/${r.id}/dist (${Math.round(r.js / 1024)} KB of script)`); }
}

if (require.main === module) main();
module.exports = { buildModule };
