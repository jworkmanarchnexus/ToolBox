"""Generate the embedded assets for the single-file build.

- fonts.css   : @font-face rules for Lato and Roboto Condensed (latin subset, woff2, base64)
- pdffonts.js : the same fonts as TTF (base64) for vector PDF export through jsPDF
- icons.js    : the line icons used by the app (Lucide, ISC license), as SVG strings

Sources come from npm packages (@fontsource/lato, @fontsource/roboto-condensed, lucide-static),
installed into FONT_NODE_MODULES. Production should self-host the woff2 files in assets/fonts
instead of embedding them; the embedded copy exists only because the preview is one HTML file.
"""
import base64, io, os, re, shutil, sys
from fontTools.ttLib import TTFont

NM = os.environ.get('FONT_NODE_MODULES', '/tmp/fonts/node_modules')
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

FONTS = [
    # css family, weight, fontsource file, pdf family, pdf style
    ('Lato', 400, '@fontsource/lato/files/lato-latin-400-normal.woff2', 'Lato', 'normal'),
    ('Lato', 700, '@fontsource/lato/files/lato-latin-700-normal.woff2', 'Lato', 'bold'),
    ('Roboto Condensed', 400, '@fontsource/roboto-condensed/files/roboto-condensed-latin-400-normal.woff2', 'RobotoCondensed', 'normal'),
    ('Roboto Condensed', 700, '@fontsource/roboto-condensed/files/roboto-condensed-latin-700-normal.woff2', 'RobotoCondensed', 'bold'),
]

ICONS = '''arrow-left chevron-down chevron-right chevron-left chevrons-up-down plus search calendar calendar-clock lock lock-open link
unlink trash-2 copy undo-2 redo-2 history settings sliders-horizontal download share-2 eye filter list chart-gantt table-2 sheet columns-2
panel-left triangle-alert circle-alert octagon-alert info check x ellipsis grip-vertical diamond flag target zoom-in zoom-out scan
crosshair folder folder-open archive star users layout-grid rows-3 clock file-text printer image file-spreadsheet sun moon menu keyboard
circle-help arrow-up arrow-down corner-down-right pencil arrow-right-left list-plus briefcase layout-list circle-check circle-dot hourglass
external-link layout-template square-pen file-plus-2 house panel-left-close panel-left-open move-horizontal minus arrow-right milestone
git-merge cloud-check user rotate-ccw sigma'''.split()


def main():
    os.makedirs(os.path.join(ROOT, 'assets', 'fonts'), exist_ok=True)
    css = ['/* Generated by tools/gen-assets.py. Lato and Roboto Condensed: SIL Open Font License 1.1 (assets/fonts). */']
    pdf = ['/* Generated by tools/gen-assets.py. TTF copies of the UI fonts so PDF export can embed real text. OFL 1.1. */',
           'const PDF_FONTS = [']
    for fam, w, src, pfam, pstyle in FONTS:
        path = os.path.join(NM, src)
        data = open(path, 'rb').read()
        name = os.path.basename(src)
        shutil.copy(path, os.path.join(ROOT, 'assets', 'fonts', name))
        css.append("@font-face { font-family: '%s'; font-style: normal; font-weight: %d; font-display: swap; src: url(data:font/woff2;base64,%s) format('woff2'); }"
                   % (fam, w, base64.b64encode(data).decode()))
        t = TTFont(io.BytesIO(data))
        t.flavor = None
        buf = io.BytesIO()
        t.save(buf)
        ttf = buf.getvalue()
        open(os.path.join(ROOT, 'assets', 'fonts', name.replace('.woff2', '.ttf')), 'wb').write(ttf)
        pdf.append("  { file: '%s', family: '%s', style: '%s', data: '%s' }," % (name.replace('.woff2', '.ttf'), pfam, pstyle, base64.b64encode(ttf).decode()))
    pdf.append('];')
    open(os.path.join(ROOT, 'fonts.css'), 'w').write('\n'.join(css) + '\n')
    open(os.path.join(ROOT, 'pdffonts.js'), 'w').write('\n'.join(pdf) + '\n')

    out = ['/* Generated by tools/gen-assets.py. Line icons from Lucide (ISC license, assets/LUCIDE-LICENSE.txt). */', 'const ICONS = {']
    for n in ICONS:
        svg = open(os.path.join(NM, 'lucide-static', 'icons', n + '.svg')).read()
        inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
        inner = re.sub(r'\s+', ' ', inner).replace(' />', '/>').strip()
        inner = re.sub(r'>\s+<', '><', inner)
        out.append("  '%s': '%s'," % (n, inner.replace("'", "\\'")))
    out.append('};')
    out.append("""/* one icon as an SVG string: inherits color; decorative unless a label is given */
function icon(name, size, label) {
  const s = size || 16, body = ICONS[name] || '';
  return '<svg class="ico-svg" viewBox="0 0 24 24" width="' + s + '" height="' + s + '" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"'
    + (label ? ' role="img" aria-label="' + label + '"' : ' aria-hidden="true"') + '>' + body + '</svg>';
}""")
    open(os.path.join(ROOT, 'icons.js'), 'w').write('\n'.join(out) + '\n')
    lic = os.path.join(NM, 'lucide-static', 'LICENSE')
    if os.path.exists(lic):
        shutil.copy(lic, os.path.join(ROOT, 'assets', 'LUCIDE-LICENSE.txt'))
    print('ok', len(ICONS), 'icons')


if __name__ == '__main__':
    main()
